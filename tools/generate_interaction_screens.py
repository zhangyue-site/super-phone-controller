"""200x200 interaction screens. Rectangles match touch_ui.h exactly."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
ROOT=Path(__file__).resolve().parents[1]
FONT='/System/Library/Fonts/STHeiti Medium.ttc'
if not Path(FONT).exists(): FONT='/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc'
assets=[]
def text(im,xy,label,size=16,center=False):
    d=ImageDraw.Draw(im); f=ImageFont.truetype(FONT,size)
    assert d.textlength(label,font=f)<=184, label
    x,y=xy
    if center:x-=d.textlength(label,font=f)/2
    d.text((x,y),label,font=f,fill=0)
def base(title,hint):
    im=Image.new('1',(200,200),1)
    text(im,(8,2),title,20);text(im,(8,29),hint,12)
    return im
def button(im,box,label,size=22):
    ImageDraw.Draw(im).rectangle(box,outline=0,width=2)
    x0,y0,x1,y1=box;text(im,((x0+x1)/2,y0+8),label,size,True)
def emit(name,frames,preview):
    for i,im in enumerate(frames):
        assert im.size==(200,200)
        # Stable footer; version is separately rendered at 188..199.
        ImageDraw.Draw(im).rectangle((0,162,199,187),fill=1)
        ImageDraw.Draw(im).line((8,162,191,162),fill=0)
        ImageDraw.Draw(im).line((100,162,100,186),fill=0)
        text(im,(50,166),'首页/A双击',12,True);text(im,(150,166),'停止/B长按',12,True)
        im.save(ROOT/'previews'/f'{preview}-{i}.png')
    rows=['{'+','.join(map(str,im.tobytes()))+'}' for im in frames]
    assets.append('static const unsigned char '+name+'['+str(len(rows))+'][5000]={'+','.join(rows)+'};')
homes=[]
for state in ['等待连接','连接待检测','准备就绪','已停止']:
    im=Image.new('1',(200,200),1)
    text(im,(8,4),state,28)
    text(im,(8,36),'短按 A 翻页 · B 双击声音',13)
    button(im,(8,55,191,154),'按住 A 说话',26)
    text(im,(100,116),'松开后发送',19,True)
    homes.append(im)
emit('interaction_home',homes,'interaction-home')
manual=[]
for title,top,bottom in [('手机按键','手机首页','手机返回'),('左右移动','向左','向右'),('上下移动','向上','向下'),('点击操作','点击','停止任务')]:
    im=base(title,'上滑下一页 · 下滑上一页')
    button(im,(8,45,191,99),top);button(im,(8,105,191,154),bottom)
    manual.append(im)
emit('interaction_manual',manual,'interaction-manual')
sound=[]
for muted in (False,True):
    for volume in range(0,101,20):
        im=base('声音 · 静音' if muted else '声音 · 播报','短按 A 加 · B 减')
        text(im,(100,51),f'{volume}%',42,True)
        text(im,(25,58),'−',26,True);text(im,(175,58),'+',26,True)
        button(im,(8,108,95,153),'恢复' if muted else '静音',20);button(im,(104,108,191,153),'试听',20)
        sound.append(im)
emit('interaction_sound',sound,'interaction-sound')
ota=[]
for hint in ['通过手机网络检查新版本','检查更新中，请稍等','下载固件中，请稍等','校验通过，准备重启','已是最新版本','更新失败，可重新检查']:
    im=base('固件更新',hint)
    button(im,(8,45,191,99),'检查更新');button(im,(8,105,191,154),'返回首页')
    ota.append(im)
emit('interaction_ota',ota,'interaction-ota')
ble=[]
for hint in ['等待手机发送固件','正在接收，请保持靠近','正在校验固件','校验通过，即将重启','更新失败，请在手机重试']:
    im=base('蓝牙升级',hint)
    text(im,(100,76),'请保持供电',22,True)
    text(im,(100,118),'提交启动槽后无法中断',13,True)
    ble.append(im)
emit('interaction_ble',ble,'interaction-ble')
voice=[]
for title,hint,detail in [
    ('语音待命','按住 A 说话','松开后发送'),
    ('正在录音','松开 A 发送','B 长按停止'),
    ('正在识别','请稍等','B 长按停止'),
    ('已识别','请查看交互页','尚未执行手机操作'),
    ('准备麦克风','请继续按住 A','B 长按停止'),
    ('识别失败','按住 A 重试','靠近麦克风说话'),
    ('尚未连接','按住 A 检测','请检查手机连接'),
    ('正在连接','请查看手机授权','B 长按停止'),
    ('连接已建立','松开后重新按住 A','开始说话'),
    ('连接失败','按住 A 重试','请检查手机授权'),
]:
    im=Image.new('1',(200,200),1)
    text(im,(100,20),title,28,True);text(im,(100,77),hint,18,True);text(im,(100,119),detail,15,True)
    voice.append(im)
emit('interaction_voice',voice,'interaction-voice')
# Footer-only strip shared by every screen.
im=homes[0]
strip=im.crop((0,162,200,188)).tobytes()
assets.append('static const unsigned char interaction_footer[650]={'+','.join(map(str,strip))+'};')
(ROOT/'firmware-epaper/main/interaction_screens.h').write_text('// Generated by tools/generate_interaction_screens.py\n#pragma once\n'+'\n'.join(assets)+'\n')
