"""UI-only monochrome labels; no transport or authorization state changes."""
from pathlib import Path
import re
from PIL import Image, ImageDraw, ImageFont
root=Path(__file__).resolve().parents[1]
main=root/'firmware-epaper/main'
font_path='/usr/share/fonts/google-noto-cjk/NotoSansCJK-Regular.ttc'
font=ImageFont.truetype(font_path,23,index=0)
small=ImageFont.truetype(font_path,20,index=0)
def label(image,text,y,height,face):
 d=ImageDraw.Draw(image);d.rectangle((0,y,199,y+height-1),fill=1)
 box=d.textbbox((0,0),text,font=face)
 width=box[2]-box[0];h=box[3]-box[1]
 assert width<=196 and h<=height
 d.text(((200-width)//2-box[0],y+(height-h)//2-box[1]),text,font=face,fill=0)
def array(name,images):
 raw=[list(image.tobytes()) for image in images]
 return 'static const unsigned char '+name+'['+str(len(raw))+']['+str(len(raw[0]))+']={'+','.join('{'+','.join(map(str,row))+'}' for row in raw)+'};\n'
s=(main/'interaction_screens.h').read_text()
values=list(map(int,re.findall(r'\d+',s.split('interaction_home[4][5000]=',1)[1].split(';',1)[0])))
base=Image.frombytes('1',(200,200),bytes(values[:5000]))
homes=[];strips=[]
out=root.parent/'display-preview';out.mkdir(exist_ok=True)
for i,text in enumerate(('手机蓝牙已连接','手机控制中')):
 im=base.copy();label(im,text,0,31,font);homes.append(im);im.save(out/('home-'+str(i)+'.png'))
for i,text in enumerate(('手机蓝牙已连接','手机控制中','板端直连未连')):
 im=Image.new('1',(200,26),1);label(im,text,0,26,small);strips.append(im);im.save(out/('strip-'+str(i)+'.png'))
(main/'relay_screens.h').write_text('// Generated by tools/generate_relay_screens.py; 200x200 homes and200x26 footers.\n#pragma once\n'+array('relay_home',homes)+array('relay_strips',strips))
