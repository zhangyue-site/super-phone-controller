"""Local consent screens: offline, reproducible, contains no device secrets."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
root=Path(__file__).resolve().parents[1]
font='/System/Library/Fonts/Supplemental/Songti.ttc'
if not Path(font).exists():font='/usr/share/fonts/google-noto-cjk/NotoSansCJK-Regular.ttc'
arrays=[]
for enabled in (False,True):
 im=Image.new('1',(200,200),1);d=ImageDraw.Draw(im)
 for x,y,s,size in [(9,6,'USB 控制',20),(9,39,'当前：'+('已开启' if enabled else '已关闭'),17),
  (9,71,'长按 BOOT 两秒',16),(9,96,'确认'+('关闭' if enabled else '开启鼠标 / 键盘'),15),
  (9,126,'短按取消 · 15 秒超时',13),(9,150,'每次重启自动关闭',13),(9,176,'蓝牙关闭 · 本地确认',12)]:
  f=ImageFont.truetype(font,size)
  assert d.textlength(s,font=f)<=182,(s,d.textlength(s,font=f))
  d.text((x,y),s,font=f,fill=0)
 data=im.tobytes();assert len(data)==5000
 name='mode_enabled_screen' if enabled else 'mode_disabled_screen'
 arrays.append('static const unsigned char '+name+'[5000]={'+','.join(map(str,data))+'};')
 (root/'previews').mkdir(exist_ok=True);im.save(root/'previews'/('usb-enabled.png' if enabled else 'usb-disabled.png'))
(root/'firmware-epaper/main/mode_screens.h').write_text('// Generated by tools/generate_mode_screens.py\n#pragma once\n'+'\n'.join(arrays)+'\n')
